"""Заданные константы библиотеки: одно объявление на величину.

Правило: если значение встречается больше чем в одном месте, оно объявляется
здесь и импортируется. Прежде одни и те же числа стояли и в этом файле,
и голыми литералами в сигнатурах (0.006 в пяти функциях, 0.05 в шести,
0.010 в двух), из-за чего изменение величины требовало помнить все места сразу,
а расхождение между ними ничем не отличалось от опечатки.

Значения, встречающиеся ровно один раз, остаются в сигнатуре своей функции:
выносить их сюда значило бы разлучать величину с единственным местом,
где она имеет смысл.

Разбиты на группы, и различие между группами содержательное:

* **физиология глаза** -- свойства глаза, а не записи и не настройки. Служат
  границами, за которые модельная оценка не выходит;
* **требования методики к записи** -- сколько отсчётов должно приходиться
  на событие, чтобы его вообще можно было измерить;
* **значения по умолчанию** -- то, что пользователь волен задать иначе;
  заданное им всегда важнее;
* **унаследованные значения** (`LEGACY_`) -- то, что осталось от прежней
  реализации и намеренно не выводится из частоты записи.

Отдельно стоят константы разбиения и склейки: они выведены в параметры
функций, чтобы их можно было менять, не трогая код.
"""
from __future__ import annotations

from typing import NoReturn

# ═══════════════════════════════════════════════════ физиология глаза
#: Радиус сферы, по которой движется зрачок, мм. Антропометрическая константа,
#: а не параметр прибора. Через неё линейное смещение переводится в угол:
#: `atan2(смещение - нейтраль, EYE_RADIUS_MM)`. Единицы связаны именно ею,
#: поэтому смещение обязано быть в миллиметрах.
EYE_RADIUS_MM: float = 12.0

#: Физиологический предел скорости глаза, град/с. Быстрее -- артефакт записи.
MAX_EYE_VELOCITY_DEG_S: float = 900.0

#: Скорость идеальной фовеальной фиксации, град/с. Физиологический предел:
#: медленнее этого взор на фиксации не бывает, поэтому порог скорости
#: на фиксации не может быть строже. Чем выше частота записи, тем ближе
#: достижимый порог к этому значению; по оценке автора методики оно становится
#: релевантным начиная примерно с 900 Гц.
IDEAL_FIXATION_VELOCITY_DEG_S: float = 5.0

#: Пространственный разброс идеальной фовеальной фиксации, град: поперечник фовеа.
IDEAL_FIXATION_SPREAD_DEG: float = 5.0

#: Минимальная физиологическая длительность фиксации, с: короче интервал
#: фиксацией не является. Нижняя граница интервала, на котором смещение взора
#: ещё считается фиксационным.
MIN_FIXATION_DURATION_S: float = 0.050

# ═══════════════════════════════════════ требования методики к записи
#: Сколько отсчётов записи должно приходиться на **саккаду**. Четыре, потому что
#: по саккаде восстанавливается модель главной последовательности: чтобы судить
#: о форме движения, а не только о факте его наличия, отсчётов нужно больше.
N_SAMPLES_SACCADE: int = 4

#: Сколько отсчётов должно приходиться на **перевод взора**. Три: требования
#: к произвольному переводу взора ниже, чем к саккаде, потому что модель
#: по нему не восстанавливается -- достаточно уверенно выделить событие.
#:
#: Значения намеренно разные, и это не рассогласование: саккада -- движение
#: глаза относительно головы, перевод взора включает и движение головы,
#: и это разные величины с разными требованиями. Прежде оба стояли в коде
#: голыми числами (4 в сигнатуре модели, 3 в сигнатурах разметки), и разницу
#: нельзя было отличить от опечатки.
N_SAMPLES_GAZE_SHIFT: int = 3

# ═══════════════════════════════════════════════ значения по умолчанию
#: Минимальная длительность события, с: ниже неё пик скорости событием
#: не признаётся.
DEFAULT_MIN_EVENT_DURATION_S: float = 0.006

#: Допустимое расхождение осей по времени при подгонке сигмоидой, с. Совпадение
#: с `DEFAULT_MIN_EVENT_DURATION_S` историческое: обе роли играл один параметр
#: `max_delta_time`, разделённый в пункте C-5. Связи между величинами нет,
#: и менять их следует независимо.
DEFAULT_MAX_AXIS_DT_S: float = 0.006

#: Окно, по которому считается скорость для критерия фиксации, с: `|dp| / w`.
#: Поотсчётная разность не годится -- её шум растёт с частотой записи, тогда как
#: модельный порог с частотой падает.
DEFAULT_FIXATION_VELOCITY_WINDOW_S: float = 0.010

#: Уровень значимости критерия наклона: дрейф вместо удержания.
DEFAULT_TREND_ALPHA: float = 0.05

#: Уровень покрытия эллипса рассеяния. 0.90 отвечает k = ln(10) ~ 2.3 --
#: значение, принятое в литературе по BCEA.
DEFAULT_BCEA_PROBABILITY: float = 0.90

#: Минимальный разрыв в потоке достоверных отсчётов, считающийся морганием, с.
DEFAULT_MIN_BLINK_GAP_S: float = 0.050

#: Окно поиска смены монотонности при уточнении границ моргания, с.
DEFAULT_REFINE_SEARCH_S: float = 0.100

# ═══════════════════════════════════ разбиение интервала и склейка
#: Мера различия, при которой разбиение обосновано при значимом p-value.
SPLIT_SCORE_MIN_WITH_PVALUE: float = 1.0

#: Мера различия, достаточная сама по себе, в обход статистики.
SPLIT_SCORE_MIN_ALONE: float = 2.5

#: Вес ковариационного члена в мере различия.
SPLIT_COV_WEIGHT: float = 0.5

#: Уровень значимости тестов однородности (Уэлч и Левен по каждой координате).
SPLIT_ALPHA: float = 0.01

#: Минимум валидных точек в каждой половине при разбиении.
SPLIT_MIN_POINTS: int = 5

#: Допустимое относительное отличие статистик при склейке.
MERGE_STAT_TOLERANCE: float = 0.2

# ══════════════════════ разметка на базе аппроксимации сигмоидой
#: Уровни логистической кривой, по которым определяются границы события: доли
#: от её полного размаха. Событие -- участок между `p_lo` и `p_hi`.
DEFAULT_SIGMOID_P_LO: float = 0.03
DEFAULT_SIGMOID_P_HI: float = 0.97

#: Окно вокруг пика, на котором подгоняется кривая, с.
DEFAULT_SIGMOID_WINDOW_S: float = 0.15

#: Минимальное качество подгонки: ниже -- событие отбрасывается.
DEFAULT_SIGMOID_R2_MIN: float = 0.96

#: Минимальная высота пика скорости, град/с, и минимальная амплитуда, град.
#: Здесь, в отличие от разметки по порогу скорости, значения не выводятся
#: из частоты записи: это унаследованные константы, оставленные без изменений.
LEGACY_SIGMOID_MIN_PEAK_VELOCITY_DEG_S: float = 15.0
LEGACY_SIGMOID_MIN_AMPLITUDE_DEG: float = 1.0

# ══════════════════════════════════ модель траектории саккады
#: Шаг безразмерного времени при интегрировании модели.
DEFAULT_SACCADE_MODEL_DT: float = 0.001

#: Частота, на которой строится модельная кривая саккады, Гц.
DEFAULT_SACCADE_TEMPLATE_FS_HZ: float = 1000.0

# ══════════════════════════════════════════ унаследованные значения
#: Минимальная ширина пика в отсчётах в унаследованной схеме подгонки сигмоидой.
LEGACY_MIN_PEAK_WIDTH_POINTS: int = 3

#: Сигма гауссова сглаживания в отсчётах там же.
LEGACY_GAUSSIAN_SIGMA_POINTS: float = 1.5


# ═════════════════════════════════════════════ переименованные константы
#: Прежнее имя -> новое. Оба прежних имени называли физиологические величины
#: «значениями по умолчанию», хотя ни радиус глаза, ни минимальная длительность
#: фиксации настройками не являются: это свойства глаза, а не выбор пользователя.
RENAMED_CONSTANTS: dict[str, str] = {
    "DEFAULT_EYE_RADIUS_MM": "EYE_RADIUS_MM",
    "DEFAULT_MIN_FIXATION_DURATION_S": "MIN_FIXATION_DURATION_S",
}


def renamed_constant(name: str) -> NoReturn:
    """Объясняет переименование константы; для прочих имён -- обычный `AttributeError`.

    Вызывается из `__getattr__` тех модулей, где прежнее имя было публичным.
    """
    new = RENAMED_CONSTANTS.get(name)
    if new is None:
        raise AttributeError(name)
    raise NotImplementedError(
        f"константа {name} переименована в {new} и объявлена в "
        f"eyetracking_analytics.constants. Приставка DEFAULT_ означала бы "
        f"значение по умолчанию, которое пользователь волен заменить, а это "
        f"физиологическая величина -- свойство глаза, а не настройка. "
        f"Значение не изменилось."
    )
