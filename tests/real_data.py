"""Реальная запись для тестов: обезличенный отрывок.

Синтетика проверяет, что методика делает то, что задумано, на данных, у которых
известен правильный ответ. Реальная запись проверяет другое -- что код вообще
доживает до конца на том, что выдаёт прибор: неравномерный шаг, пропуски,
выбросы выше физиологического предела скорости, участки без глаза.

**Что за запись.** Отрывок 20 с из записи в шлеме VR со встроенным айтрекером
(Vive Pro Eye, 90 Гц) из проекта автора. Прибор пишет две ориентации:

* `head_q_*` -- ориентация головы в неподвижном пространстве;
* `eye_q_*` -- ориентация глаза относительно головы.

То есть ровно те две величины, из которых складывается взор, -- поэтому отрывок
годится и для входного слоя `direction`, и для разметки, и для проверки того,
что без учёта головы получается движение глаза, а не взор.

**Как обезличено.** Оставлены только время и восемь компонент двух кватернионов.
Не сохраняются: дата и время записи (время идёт от нуля), имя участника, имя
файла и каталога исходной записи, номер сессии, открытость век, положения глаз
и головы в пространстве, любые столбцы прибора кроме перечисленных. По самому
сигналу человек не идентифицируется: это направление взгляда, а не изображение
глаза и не зрачковые размеры.

Единственный экземпляр файла -- `tests/data/real_vr_head_eye_90hz.csv`.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

#: Отрывок реальной записи; путь один на все тесты.
REAL_VR_PATH = Path(__file__).parent / "data" / "real_vr_head_eye_90hz.csv"

#: Имена столбцов кватерниона, которых ждёт `direction`: порядок фиксирован.
QUATERNION_COLUMNS = ("q_x", "q_y", "q_z", "q_w")


def vr_head_eye() -> pd.DataFrame:
    """Отрывок как есть: `T_s` и по четыре компоненты на голову и на глаз."""
    return pd.read_csv(REAL_VR_PATH)


def quaternions(data: pd.DataFrame, what: str) -> pd.DataFrame:
    """Кватернионы одной величины (`"head"` либо `"eye"`) под именами `direction`."""
    cols = [f"{what}_q_{axis}" for axis in "xyzw"]
    return data.loc[:, cols].rename(columns=dict(zip(cols, QUATERNION_COLUMNS)))
